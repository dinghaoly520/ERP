/**
 * 删除审查任务前的确认文案（审计第 3 处跟进，2026-11-26）。
 *
 * 任务栏里是在跑的任务，报告面板里是已结束的记录，两处删除的后果不同，文案分开说：
 *  - 在跑的：删除会立即停止审查（与「停止任务」是同一个动作，只是连记录一起删）；
 *  - 已结束的：这份上传的源文件在没有别的审查记录使用时会一并删除。
 */
export function deleteReviewConfirmMessage(status: string): string {
  if (status === 'running' || status === 'pending') {
    return '该任务正在审查中，删除后会立即停止审查，本次不保留审查结果。\n\n确定删除？';
  }
  return '确定删除该审查记录？\n\n没有其他审查记录在用的上传源文件会一并删除，删除后无法恢复。';
}
