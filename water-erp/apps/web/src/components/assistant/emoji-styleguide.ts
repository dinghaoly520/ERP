/** 随机选一个，避免重复感 */
export function pickRandom<T extends readonly string[]>(arr: T): T[number] {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 问候场景：根据时段选 */
export function greetByHour(hour: number): string {
  if (hour < 6) return "🌙";
  if (hour < 9) return "🌸";
  if (hour < 12) return "☀️";
  if (hour < 14) return "🍃";
  if (hour < 18) return "🌤️";
  return "🌆";
}
